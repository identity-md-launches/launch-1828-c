// Generates typed ABIs from the Foundry build of this repository (run `forge build` at the repo root first).
// Writes src/abi/<Contract>.ts and reports keccak256 of the canonical ABI JSON against deployment abiHash values.
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256, toBytes } from "viem";

const NAMES = ["MockUSDC", "MockCardNFT", "CardPool", "CardOracle", "CardLending"];
// abiHash values recorded in the launch's deployment.json (source commit ef5a93b).
const EXPECTED = {
  MockUSDC: "a89dddd2831b4f1324fb1f67d8fd53b38abdfb237090e89ae8119d5faee93fee",
  MockCardNFT: "a66f0770185c57372286b47c1924cfdf8e855794b581d3ed14aff0e850949bf9",
  CardPool: "7403958739baee8dd444c796f0d1ed02edda2a048c32bc369abbf1bd83043219",
  CardOracle: "f6c64d65c2e3ce128ba2b9fb17e5b5b3653b554a5119c028be7b779f7f738e11",
  CardLending: "67e0f34899d5503ac608c7ac49c5d41796a8da1f5c4439fa2b2066b36b47fbf3",
};
const canon = (v) =>
  Array.isArray(v) ? `[${v.map(canon).join(",")}]`
  : v && typeof v === "object" ? `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canon(v[k])}`).join(",")}}`
  : JSON.stringify(v);
const report = {};
// Keep the public catalogue's runtime ABI small. Full generated ABIs remain available to the
// lazy transaction pages; these entries are copied from the same build, never handwritten.
const READS = {
  MockUSDC: ["balanceOf", "allowance"],
  MockCardNFT: ["ownerOf", "cardData", "classId", "CardMinted", "Transfer"],
  CardPool: ["totalAssets", "availableLiquidity", "reserve", "coveredReserve", "totalSupply", "convertToAssets", "paused", "lending", "balanceOf", "maxWithdraw", "Deposit", "Withdraw", "Settled"],
  CardOracle: ["template", "freshPrice", "prices", "pendingForClass", "request", "panelSize", "quorum", "oracleSigner", "requestFee", "paymentAsset", "paused", "submit", "onPrice", "ClassSet", "Requested", "PriceStored", "Failed", "TimedOut", "OracleSignerSet"],
  CardLending: ["aprBps", "nextLoanId", "netReceivable", "paused", "loan", "auctionMark", "surplus", "Borrowed", "Extended", "Repaid", "Purchased", "AuctionStarted"],
};
let reads = "// Generated by scripts/gen-abi.mjs from the same Foundry ABIs as the full exports.\n";
for (const n of NAMES) {
  const abi = JSON.parse(readFileSync(new URL(`../../out/${n}.sol/${n}.json`, import.meta.url))).abi;
  const sorted = keccak256(toBytes(canon(abi))).slice(2);
  const plain = keccak256(toBytes(JSON.stringify(abi))).slice(2);
  report[n] = { expected: EXPECTED[n], canonical: sorted, compact: plain, match: sorted === EXPECTED[n] || plain === EXPECTED[n] };
  writeFileSync(new URL(`../src/abi/${n}.ts`, import.meta.url),
    `// Generated by scripts/gen-abi.mjs from out/${n}.sol/${n}.json. Do not edit.\nexport const ${n}Abi = ${JSON.stringify(abi, null, 1)} as const;\n`);
  const subset = abi.filter((entry) => READS[n].includes(entry.name));
  if (subset.length !== READS[n].length) throw new Error(`Missing or overloaded read ABI for ${n}`);
  reads += `export const ${n}ReadAbi = ${JSON.stringify(subset, null, 1)} as const;\n`;
}
writeFileSync(new URL("../src/abi/reads.ts", import.meta.url), reads);
writeFileSync(new URL("../src/abi/hashes.json", import.meta.url), JSON.stringify(report, null, 2) + "\n");
console.log(JSON.stringify(report, null, 2));
